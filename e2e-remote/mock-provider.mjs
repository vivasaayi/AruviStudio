import http from "node:http";

let workflowCalls = 0;
let workflowPrompts = [];
let workflowRequests = [];
let coordinatorCodingCalls = 0;
let streamDisconnects = 0;
let lastCopilotRequest = null;
let copilotCalls = 0;
const workflowOutputs = [
  "requirement analysis complete",
  "planning complete",
  JSON.stringify({ type: "tool_call", tool: "repo.write_file", reason: "implement test task", arguments: { path: "src/generated.txt", content: "generated by workflow test\n" } }),
  JSON.stringify({ type: "final", summary: "coding complete", result: "implemented" }),
  "unit test generation complete", "integration test generation complete", "ui test planning complete",
  "qa validation complete", "security review complete", "performance review complete",
];

const server = http.createServer((request, response) => {
  response.setHeader("Content-Type", "application/json");
  if (request.method === "GET" && request.url === "/copilot/last") {
    response.end(JSON.stringify(lastCopilotRequest));
  } else if (request.method === "GET" && request.url === "/copilot/stats") {
    response.end(JSON.stringify({ calls: copilotCalls }));
  } else if (request.method === "GET" && request.url === "/stream/stats") {
    response.end(JSON.stringify({ disconnects: streamDisconnects }));
  } else if (request.method === "POST" && request.url === "/workflow/reset") {
    workflowCalls = 0;
    workflowPrompts = [];
    workflowRequests = [];
    response.end(JSON.stringify({ ok: true }));
  } else if (request.method === "GET" && request.url === "/workflow/prompts") {
    response.end(JSON.stringify(workflowPrompts));
  } else if (request.method === "GET" && request.url === "/workflow/requests") {
    response.end(JSON.stringify(workflowRequests));
  } else if (request.method === "POST" && request.url === "/coordinator/reset") {
    coordinatorCodingCalls = 0;
    response.end(JSON.stringify({ ok: true }));
  } else if (request.method === "POST" && request.url === "/coordinator/v1/chat/completions") {
    const chunks = [];
    request.on("data", (chunk) => chunks.push(chunk));
    request.on("end", () => {
      let messages;
      try { messages = JSON.parse(Buffer.concat(chunks).toString("utf8")).messages; }
      catch { response.statusCode = 400; return response.end(JSON.stringify({ error: "Invalid coordinator request" })); }
      const coding = JSON.stringify(messages).includes("Use tool-calling JSON to inspect files");
      const content = coding ? (coordinatorCodingCalls++ === 0
        ? JSON.stringify({ type: "tool_call", tool: "repo.write_file", reason: "coordinator fixture", arguments: { path: "src/coordinator-generated.txt", content: "coordinator workflow fixture\n" } })
        : JSON.stringify({ type: "final", summary: "coding complete", result: "implemented" })) : "Coordinator fixture stage complete";
      response.end(JSON.stringify({ choices: [{ message: { role: "assistant", content } }], usage: { prompt_tokens: 12, completion_tokens: 4 } }));
    });
  } else if (request.method === "GET" && request.url === "/legacy/v1/models") {
    if (request.headers.authorization !== "Bearer synthetic-legacy-key-12345") response.statusCode = 401;
    response.end(JSON.stringify(response.statusCode === 401 ? { error: "unauthorized" } : { data: [{ id: "browser-test-model" }] }));
  } else if (request.method === "GET" && request.url === "/credential/v1/models") {
    if (request.headers.authorization !== "Bearer synthetic-rotation-key-12345") response.statusCode = 401;
    response.end(JSON.stringify(response.statusCode === 401 ? { error: "unauthorized" } : { data: [{ id: "browser-test-model" }] }));
  } else if (request.method === "GET" && request.url === "/v1/models") {
    response.end(JSON.stringify({ data: [{ id: "browser-test-model" }] }));
  } else if (request.method === "POST" && request.url === "/workflow/v1/chat/completions") {
    const content = workflowOutputs[workflowCalls++] || "review complete";
    const chunks = [];
    request.on("data", (chunk) => chunks.push(chunk));
    request.on("end", () => {
      try { const body = JSON.parse(Buffer.concat(chunks).toString("utf8")); workflowPrompts.push(body.messages); workflowRequests.push({ response_format: body.response_format ?? null }); }
      catch { response.statusCode = 400; return response.end(JSON.stringify({ error: "Invalid workflow request" })); }
      response.end(JSON.stringify({ choices: [{ message: { role: "assistant", content } }], usage: { prompt_tokens: 12, completion_tokens: 4 } }));
    });
  } else if (request.method === "POST" && request.url === "/malformed/v1/chat/completions") {
    request.resume(); request.on("end", () => response.end(JSON.stringify({ choices: [{ message: { content: [{ type: "text", text: "partial" }, { type: "image", url: "fixture" }] }, finish_reason: "stop" }] })));
  } else if (request.method === "POST" && request.url === "/anthropic-malformed/v1/messages") {
    request.resume(); request.on("end", () => response.end(JSON.stringify({ content: [{ type: "text", text: "partial" }, { type: "text", text: null }], stop_reason: "end_turn" })));
  } else if (request.method === "POST" && request.url === "/anthropic/v1/messages") {
    const chunks = []; request.on("data", (chunk) => chunks.push(chunk));
    request.on("end", () => {
      let body; try { body = JSON.parse(Buffer.concat(chunks).toString("utf8")); } catch { response.statusCode = 400; return response.end(); }
      if (request.headers["x-api-key"] !== "synthetic-anthropic-key" || !request.headers["anthropic-version"] || !body.stream || !body.system || body.messages.some((message) => message.role === "system")) {
        response.statusCode = 400; return response.end(JSON.stringify({ error: "Invalid Anthropic request" }));
      }
      response.setHeader("Content-Type", "text/event-stream");
      response.write('data: {"type":"message_start","message":{"id":"fixture","usage":{"input_tokens":17}}}\n\n');
      response.write('data: {"type":"content_block_delta","delta":{"type":"text_delta","text":"Claude "}}\n\n');
      const last = body.messages.at(-1)?.content || "";
      setTimeout(() => {
        if (response.destroyed) return;
        if (last.includes("stream failure")) return response.end('data: {"type":"message_delta","delta":{"stop_reason":"max_tokens"}}\n\n');
        response.write('data: {"type":"content_block_delta","delta":{"type":"text_delta","text":"fixture"}}\n\n');
        response.write('data: {"type":"message_delta","delta":{"stop_reason":"end_turn"},"usage":{"output_tokens":3}}\n\n');
        response.end('data: {"type":"message_stop"}\n\n');
      }, 500);
    });
  } else if (request.method === "POST" && request.url === "/v1/audio/transcriptions") {
    const chunks = [];
    request.on("data", (chunk) => chunks.push(chunk));
    request.on("end", () => {
      const body = Buffer.concat(chunks);
      if (!request.headers["content-type"]?.startsWith("multipart/form-data") || !body.includes("RIFF") || !body.includes("synthetic-stt-model") || !body.includes("en-US")) {
        response.statusCode = 400;
        response.end(JSON.stringify({ error: "Unexpected transcription payload" }));
        return;
      }
      response.end(JSON.stringify({ text: "Synthetic microphone transcript" }));
    });
  } else if (request.method === "POST" && request.url === "/v1/audio/speech") {
    const chunks = [];
    request.on("data", (chunk) => chunks.push(chunk));
    request.on("end", () => {
      let payload;
      try { payload = JSON.parse(Buffer.concat(chunks).toString("utf8")); } catch { response.statusCode = 400; return response.end(); }
      if (payload.model !== "synthetic-tts" || payload.response_format !== "wav") { response.statusCode = 400; return response.end(); }
      const wav = Buffer.alloc(44 + 3200);
      wav.write("RIFF", 0); wav.writeUInt32LE(wav.length - 8, 4); wav.write("WAVEfmt ", 8); wav.writeUInt32LE(16, 16);
      wav.writeUInt16LE(1, 20); wav.writeUInt16LE(1, 22); wav.writeUInt32LE(16000, 24); wav.writeUInt32LE(32000, 28);
      wav.writeUInt16LE(2, 32); wav.writeUInt16LE(16, 34); wav.write("data", 36); wav.writeUInt32LE(3200, 40);
      response.setHeader("Content-Type", "audio/wav"); response.end(wav);
    });
  } else if (request.method === "POST" && request.url === "/v1/chat/completions") {
    const chunks = []; request.on("data", (chunk) => chunks.push(chunk));
    request.on("end", () => {
      let body; try { body = JSON.parse(Buffer.concat(chunks).toString("utf8")); } catch { response.statusCode = 400; return response.end(); }
      if (body.messages?.[0]?.content?.startsWith("You are Aruvi Copilot.")) { lastCopilotRequest = body; copilotCalls++; }
      if (body.messages?.at(-1)?.content?.includes("Synthetic Copilot failure")) { response.statusCode = 500; return response.end(JSON.stringify({ error: "fixture failure" })); }
      if (body.messages?.at(-1)?.content?.includes("Synthetic long Copilot reply")) return response.end(JSON.stringify({ choices: [{ message: { role: "assistant", content: "x".repeat(100050) } }] }));
      if (!body.stream) return response.end(JSON.stringify({ choices: [{ message: { role: "assistant", content: "Container provider reply" } }], usage: { prompt_tokens: 12, completion_tokens: 4 } }));
      response.setHeader("Content-Type", "text/event-stream");
      response.on("close", () => { if (!response.writableEnded) streamDisconnects++; });
      response.write('data: {"choices":[{"delta":{"content":"First "}}]}\n\n');
      const last = body.messages.at(-1)?.content || "";
      setTimeout(() => {
        if (response.destroyed) return;
        if (last.includes("stream failure")) return response.end('data: {"choices":[{"delta":{},"finish_reason":"length"}]}\n\n');
        response.write('data: {"choices":[{"delta":{"content":"second"},"finish_reason":"stop"}]}\n\n');
        response.end('data: [DONE]\n\n');
      }, last.includes("stream cancel") ? 5000 : 500);
    });
  } else {
    response.statusCode = 404;
    response.end(JSON.stringify({ error: "Not found" }));
  }
});
server.listen(19876, "0.0.0.0");
